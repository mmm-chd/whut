export type AssetStatus = 'placeholder' | 'draft' | 'final';
export type AssetType = 'image' | 'audio' | 'font' | 'effect';

export interface AssetEntry {
  id: string;
  type: AssetType;
  path: string;
  status: AssetStatus;
  alt?: string;
  /**
   * Plays only this slice of the file, in milliseconds: [start, duration].
   * Lets two dialogue lines share one recording.
   */
  sprite?: readonly [number, number];
  /** Length of the recording (or of its slice) in milliseconds, measured by decoding it. */
  durationMs?: number;
}

function imageAsset(id: string, alt: string): AssetEntry {
  return {
    id,
    type: 'image',
    path: placeholderUrl,
    status: 'placeholder',
    alt,
  };
}

function draftImage(id: string, path: string, alt: string): AssetEntry {
  return {
    id,
    type: 'image',
    path,
    status: 'draft',
    alt,
  };
}

function finalAsset(id: string, type: AssetType, path: string, alt?: string): AssetEntry {
  return { id, type, path, status: 'final', alt };
}

function voiceAsset(
  id: string,
  path: string,
  sprite?: readonly [number, number],
  durationMs?: number,
): AssetEntry {
  return { id, type: 'audio', path, status: 'final', sprite, durationMs: sprite?.[1] ?? durationMs };
}

function deferredAsset(id: string, type: AssetType): AssetEntry {
  return {
    id,
    type,
    path: '',
    status: 'placeholder',
  };
}

